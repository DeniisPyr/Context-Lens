def test_upgrade_never_selects_the_text(before_datasets: Config, database: URL) -> None:
    insert_documents(database, "notes.txt", "notes.txt")
    statements = []

    def record(connection, cursor, statement, parameters, context, executemany) -> None:
        statements.append(statement)

    event.listen(Engine, "before_cursor_execute", record)
    try:
        command.upgrade(before_datasets, "head")
    finally:
        event.remove(Engine, "before_cursor_execute", record)

    reads = [s for s in statements if "SELECT" in s and "FROM documents" in s]
    assert any("filename" in read for read in reads)  # Proves the listener saw them.
    assert not [read for read in reads if "text" in read.lower()]


