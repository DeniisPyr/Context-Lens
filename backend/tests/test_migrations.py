def test_datasets_have_a_primary_key_and_unique_names(
    migrated: Config, database: URL
) -> None:
    inspector = inspect(create_engine(database, poolclass=NullPool))

    assert inspector.get_pk_constraint("datasets")["constrained_columns"] == ["id"]
    assert inspector.get_pk_constraint("datasets")["name"] == "pk_datasets"
    assert [
        (constraint["name"], constraint["column_names"])
        for constraint in inspector.get_unique_constraints("datasets")
    ] == [("uq_datasets_name", ["name"])]


