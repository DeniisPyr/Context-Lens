def test_upgrade_creates_the_documents_table(migrated: Config, database: URL) -> None:
    query = text(
        "SELECT column_name, data_type, is_nullable, column_default "
        "FROM information_schema.columns "
        "WHERE table_name = 'documents' ORDER BY ordinal_position"
    )
    with create_engine(database, poolclass=NullPool).connect() as connection:
        columns = [tuple(row) for row in connection.execute(query)]

    assert columns == [
        ("id", "uuid", "NO", None),
        ("filename", "text", "NO", None),
        ("text", "text", "NO", None),
        ("created_at", "timestamp with time zone", "NO", "now()"),
        ("line_count", "integer", "NO", None),
    ]


