# Rows get times from here on, in the order a test lists them.
START = datetime(2026, 1, 1, tzinfo=UTC)
INSERT_DOCUMENT = text(
    "INSERT INTO documents (id, filename, text, created_at, line_count) "
    "VALUES (:id, :filename, :text, :created_at, 1)"
)


def insert_documents(url: URL, *filenames: str) -> list[UUID]:
    # Each text is unique to its row, so a test can tell the rows apart afterwards.
    ids = [uuid4() for _ in filenames]
    rows = [
        {
            "id": id_,
            "filename": filename,
            "text": f"text of row {position}",
            "created_at": START + timedelta(minutes=position),
        }
        for position, (id_, filename) in enumerate(zip(ids, filenames, strict=True))
    ]
    with create_engine(url, poolclass=NullPool).begin() as connection:
        connection.execute(INSERT_DOCUMENT, rows)
    return ids


def filenames_by_id(url: URL) -> dict[UUID, str]:
    with create_engine(url, poolclass=NullPool).connect() as connection:
        rows = connection.execute(text("SELECT id, filename FROM documents"))
        return {row.id: row.filename for row in rows}


def filenames_in_order(url: URL) -> list[str]:
    with create_engine(url, poolclass=NullPool).connect() as connection:
        query = text("SELECT filename FROM documents ORDER BY created_at, id")
        return list(connection.scalars(query))


def dataset_names_in(url: URL) -> list[str]:
    with create_engine(url, poolclass=NullPool).connect() as connection:
        return list(connection.scalars(text("SELECT name FROM datasets ORDER BY name")))


def dataset_ids_of_documents(url: URL) -> set[UUID]:
    with create_engine(url, poolclass=NullPool).connect() as connection:
        return set(connection.scalars(text("SELECT dataset_id FROM documents")))


def preserved_columns_in(url: URL) -> dict[UUID, tuple]:
    # What a migration must not change: everything but the filename and the dataset.
    query = text("SELECT id, text, line_count, created_at FROM documents")
    with create_engine(url, poolclass=NullPool).connect() as connection:
        return {row.id: tuple(row) for row in connection.execute(query)}


def assert_upgrade_gives_these_filenames(
    config: Config, url: URL, before: list[str], after: list[str]
) -> None:
    ids = insert_documents(url, *before)

    command.upgrade(config, "head")

    assert filenames_by_id(url) == dict(zip(ids, after, strict=True))
    command.check(config)


