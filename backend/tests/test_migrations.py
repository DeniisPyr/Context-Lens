def test_deleting_a_dataset_deletes_its_documents_and_no_others(
    migrated: Config, database: URL
) -> None:
    engine = create_engine(database, poolclass=NullPool)
    keep, delete = uuid4(), uuid4()
    with Session(engine) as session:
        session.add_all(
            [DatasetRow(id=keep, name="Keep"), DatasetRow(id=delete, name="Delete")]
        )
        session.flush()
        for dataset_id in (keep, delete):
            session.add(
                DocumentRow(
                    id=uuid4(),
                    dataset_id=dataset_id,
                    filename="notes.txt",
                    text="Hello",
                    line_count=1,
                )
            )
        session.commit()

    with engine.begin() as connection:
        connection.execute(text("DELETE FROM datasets WHERE id = :id"), {"id": delete})
        remaining = connection.execute(text("SELECT dataset_id FROM documents")).all()

    assert remaining == [(keep,)]


